    fun ensureCaBundleFile(context: Context): File? {
        val outFile = File(context.filesDir, "cacert.pem")
        if (outFile.exists() && outFile.length() > 10_000L) {
            return outFile
        }

        return try {
            val sb = StringBuilder(256 * 1024)
            sb.append(MODERN_EXTRA_ROOT_PEMS).append("\n")

            // Export all trusted CAs from Android system KeyStore + Conscrypt
            try {
                val ks = KeyStore.getInstance("AndroidCAStore")
                ks.load(null, null)
                val aliases = ks.aliases()
                while (aliases.hasMoreElements()) {
                    val alias = aliases.nextElement()
                    val cert = ks.getCertificate(alias) as? X509Certificate ?: continue
                    val b64 = Base64.encodeToString(cert.encoded, Base64.DEFAULT)
                    sb.append("-----BEGIN CERTIFICATE-----\n")
                    sb.append(b64.trim()).append("\n")
                    sb.append("-----END CERTIFICATE-----\n")
                }
            } catch (e: Exception) {
                Log.w(TAG, "Failed reading AndroidCAStore", e)
            }

            // Also append any files from /system/etc/security/cacerts if AndroidCAStore was empty
            val sysCaDir = File("/system/etc/security/cacerts")
            if (sb.length < 8192 && sysCaDir.exists() && sysCaDir.isDirectory) {
                sysCaDir.listFiles()?.forEach { f ->
                    try {
                        val text = f.readText()
                        val idx = text.indexOf("-----BEGIN CERTIFICATE-----")
                        if (idx >= 0) {
                            sb.append(text.substring(idx).trim()).append("\n")
                        }
                    } catch (_: Exception) {
                    }
                }
            }

            FileOutputStream(outFile).use { fos ->
                fos.write(sb.toString().toByteArray(Charsets.US_ASCII))
                fos.flush()
            }
            outFile.setReadable(true, false)
            outFile
        } catch (e: Exception) {
            Log.w(TAG, "Could not create cacert.pem", e)
            null
        }
    }
